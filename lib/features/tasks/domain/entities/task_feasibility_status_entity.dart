/// Доступность задачи к исполнению «прямо сейчас» (движок принятия решений).
///
/// Не путать с [TaskStatusEntity]: тот описывает факт выполнения (pending / completed / archived),
/// этот enum — выполнимость при текущих ресурсах и зависимостях.
enum TaskFeasibilityStatusEntity {
  /// Не хватает денег относительно бюджетного снимка.
  blockedMoney,

  /// Не хватает материалов на складе.
  blockedMaterials,

  /// Есть незавершённые предшественники в графе зависимостей.
  blockedDependencies,

  /// Можно брать в работу.
  ready,

  /// Задача завершена с точки зрения выполнения ([TaskStatusEntity.completed]).
  done,
}
