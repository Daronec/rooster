/// Тип удалённой операции синхронизации (очередь offline-first).
enum SyncOperationType {
  /// Создание или полное обновление задачи в Firestore.
  upsertTask,

  /// Удаление задачи на сервере.
  deleteTask,

  /// Создание/обновление списка задач.
  upsertTaskList,

  /// Удаление списка задач.
  deleteTaskList,

  /// Создание или обновление плана (включая задачи внутри плана).
  upsertPlan,

  /// Удаление плана.
  deletePlan,

  /// Полная замена склада материалов пользователя в облаке.
  upsertMaterialStock,

  /// Загрузка бинарного файла (изображение) в Storage + обновление метаданных.
  uploadTaskImage,

  /// Обновление только статуса задачи (дублируется в Realtime DB отдельным шлюзом).
  patchTaskStatus,
}
